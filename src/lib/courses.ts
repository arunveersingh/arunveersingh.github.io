import { coursePresentation, type CoursePresentation } from '../data/course-presentation';

export interface OutlineDay { day: number; title: string; failure: string; phase: string; written: boolean }
export interface OutlinePage { slug: string; title: string; section: string; description: string | null }
export interface Outline {
  slug: string;
  title: string;
  tagline: string;
  source: string;
  phases: { label: string; range: string; question: string }[];
  days: OutlineDay[];
  order: number;
  unit: 'day' | 'lesson' | 'module';
  lineLabel: string | null;
  cover: string | null;
  externalUrl: string | null;
  pages: OutlinePage[];
  aliases: Record<string, string>;
}

// Generated by scripts/materialize.mjs from bundles/. Never edited by hand.
const modules = import.meta.glob<{ default: Outline }>('../data/course-outlines/*.json', { eager: true });

export const outlines: Outline[] = Object.values(modules)
  .map((m) => m.default)
  .sort((a, b) => a.order - b.order);

export function outlineFor(slug: string): Outline {
  const o = outlines.find((x) => x.slug === slug);
  if (!o) throw new Error(`No course outline for "${slug}". Is it in content-sources.json and synced?`);
  return o;
}

export const presentationFor = (slug: string): CoursePresentation => coursePresentation[slug] ?? {};

/** Card label for a course whose written days are exactly 1..N; otherwise a count. */
export function writtenDaysLabel(days: readonly { day: number; written: boolean }[]): string {
  const written = days.filter((day) => day.written).map((day) => day.day);
  if (written.length === 0) return 'Outline';
  const contiguous = written.every((day, index) => day === index + 1);
  return contiguous ? `Days 1–${written[written.length - 1]}` : `${written.length} lessons`;
}

export const lessonSlug = (day: number) => `day-${String(day).padStart(2, '0')}`;
